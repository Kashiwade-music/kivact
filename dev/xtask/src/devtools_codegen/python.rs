//! Role: Write the Python module that mirrors the protocol's types and methods.

use crate::devtools_codegen::model::{Field, Item, MethodDecl, Protocol, Ty, snake, upper_snake};

const RESERVED: [&str; 35] = [
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

/// The generated `_generated.py`.
pub(super) fn python(protocol: &Protocol) -> String {
    let mut out = format!(
        "# Generated by `cargo xtask devtools-codegen`. Do not edit.\n\
         \"\"\"Types and methods of the Kivact DevTools protocol.\"\"\"\n\
         from __future__ import annotations\n\
         from collections.abc import Callable\n\
         from dataclasses import dataclass, field\n\
         from enum import Enum, IntEnum\n\
         from typing import Any, Literal\n\
         PROTOCOL_VERSION = {}\n",
        protocol.version
    );
    let mut blocks: Vec<String> = protocol
        .items
        .iter()
        .map(|item| item_block(protocol, item))
        .collect();
    blocks.push(error_code_block(protocol));
    blocks.push(methods_block(protocol));
    for block in blocks {
        out.push('\n');
        out.push_str(&block);
        out.push('\n');
    }
    out
}

fn item_block(protocol: &Protocol, item: &Item) -> String {
    match item {
        Item::Record { name, doc, fields } => object_block(protocol, name, doc, fields, None),
        Item::Choice {
            name,
            doc,
            variants,
        } => choice_block(name, doc, variants),
        Item::Union {
            name,
            doc,
            variants,
        } => union_block(protocol, name, doc, variants),
        Item::Alias { name, ty, .. } => format!("{name} = {}", python_type(ty)),
    }
}

fn object_block(
    protocol: &Protocol,
    name: &str,
    doc: &str,
    fields: &[Field],
    kind: Option<&str>,
) -> String {
    let required: Vec<&Field> = fields
        .iter()
        .filter(|field| !has_default(&field.ty))
        .collect();
    let defaulted: Vec<&Field> = fields
        .iter()
        .filter(|field| has_default(&field.ty))
        .collect();
    let mut lines = vec![
        "@dataclass(frozen=True, slots=True)".to_owned(),
        format!("class {name}:"),
        docstring(doc, 4),
    ];
    if !fields.is_empty() || kind.is_some() {
        lines.push(String::new());
        for field in required.iter().chain(defaulted.iter()) {
            lines.push(format!(
                "    {}: {}{}",
                attr(&field.name),
                python_type(&field.ty),
                default(&field.ty)
            ));
        }
        if let Some(kind) = kind {
            lines.push(format!("    kind: Literal[\"{kind}\"] = \"{kind}\""));
        }
    }
    lines.push(String::new());
    lines.push(from_json_method(protocol, name, fields));
    lines.push(String::new());
    lines.push(to_json_method(protocol, &required, &defaulted, kind));
    lines.join("\n")
}

fn from_json_method(protocol: &Protocol, name: &str, fields: &[Field]) -> String {
    let mut lines = vec![
        "    @classmethod".to_owned(),
        format!("    def from_json(cls, data: dict[str, Any]) -> {name}:"),
    ];
    if fields.is_empty() {
        lines.push("        return cls()".to_owned());
    } else {
        let arguments = fields
            .iter()
            .map(|field| format!("{}={}", attr(&field.name), field_read(protocol, field)))
            .collect::<Vec<_>>()
            .join(", ");
        lines.push(format!("        return cls({arguments})"));
    }
    lines.join("\n")
}

fn to_json_method(
    protocol: &Protocol,
    required: &[&Field],
    defaulted: &[&Field],
    kind: Option<&str>,
) -> String {
    let mut lines = vec!["    def to_json(self) -> dict[str, Any]:".to_owned()];
    let mut pairs = Vec::new();
    if let Some(kind) = kind {
        pairs.push(format!("\"kind\": \"{kind}\""));
    }
    for field in required {
        pairs.push(format!(
            "{}: {}",
            json_key(&field.name),
            write_value(protocol, &field.ty, &format!("self.{}", attr(&field.name)))
        ));
    }
    lines.push(format!(
        "        data: dict[str, Any] = {{{}}}",
        pairs.join(", ")
    ));
    for field in defaulted {
        let name = attr(&field.name);
        match &field.ty {
            Ty::Option(inner) => {
                lines.push(format!("        if self.{name} is not None:"));
                lines.push(format!(
                    "            data[{}] = {}",
                    json_key(&field.name),
                    write_value(protocol, inner, &format!("self.{name}"))
                ));
            }
            Ty::Vec(_) => {
                lines.push(format!("        if self.{name}:"));
                lines.push(format!(
                    "            data[{}] = {}",
                    json_key(&field.name),
                    write_value(protocol, &field.ty, &format!("self.{name}"))
                ));
            }
            _ => {}
        }
    }
    lines.push("        return data".to_owned());
    lines.join("\n")
}

fn choice_block(name: &str, doc: &str, variants: &[(String, String)]) -> String {
    let mut lines = vec![format!("class {name}(str, Enum):"), docstring(doc, 4)];
    if !variants.is_empty() {
        lines.push(String::new());
    }
    for (variant, _) in variants {
        lines.push(format!(
            "    {} = {}",
            upper_snake(variant),
            py_string(&snake(variant))
        ));
    }
    lines.join("\n")
}

fn union_block(
    protocol: &Protocol,
    name: &str,
    doc: &str,
    variants: &[(String, String, Vec<Field>)],
) -> String {
    let mut blocks = Vec::new();
    for (variant, variant_doc, fields) in variants {
        let class = format!("{name}{variant}");
        blocks.push(object_block(
            protocol,
            &class,
            variant_doc,
            fields,
            Some(&snake(variant)),
        ));
    }
    let alias = variants
        .iter()
        .map(|(variant, _, _)| format!("{name}{variant}"))
        .collect::<Vec<_>>()
        .join(" | ");
    let mut alias_block = format!("{name} = {alias}");
    if !doc.trim().is_empty() {
        alias_block.push('\n');
        alias_block.push_str(&docstring(doc, 0));
    }
    blocks.push(alias_block);
    blocks.push(dispatcher(name, variants));
    blocks.join("\n\n")
}

fn dispatcher(name: &str, variants: &[(String, String, Vec<Field>)]) -> String {
    let mut lines = vec![
        format!(
            "def {}_from_json(data: dict[str, Any]) -> {name}:",
            snake(name)
        ),
        "    kind = data[\"kind\"]".to_owned(),
    ];
    for (index, (variant, _, _)) in variants.iter().enumerate() {
        let keyword = if index == 0 { "if" } else { "elif" };
        lines.push(format!(
            "    {keyword} kind == {}:",
            py_string(&snake(variant))
        ));
        lines.push(format!("        return {name}{variant}.from_json(data)"));
    }
    lines.push(format!(
        "    raise ValueError(f\"unknown {name} kind: {{kind}}\")"
    ));
    lines.join("\n")
}

fn error_code_block(protocol: &Protocol) -> String {
    let mut lines = vec![
        "class ErrorCode(IntEnum):".to_owned(),
        "    \"\"\"JSON-RPC error codes of the DevTools protocol.\"\"\"".to_owned(),
    ];
    for error in &protocol.errors {
        lines.push(String::new());
        lines.push(format!("    {} = {}", error.name, error.code));
        let doc = error.doc.split_whitespace().collect::<Vec<_>>().join(" ");
        if !doc.is_empty() {
            lines.push(docstring(&doc, 4));
        }
    }
    lines.join("\n")
}

fn methods_block(protocol: &Protocol) -> String {
    let mut lines = vec![
        "class Methods:".to_owned(),
        "    \"\"\"Every protocol method under its wire name.\"\"\"".to_owned(),
        String::new(),
        "    def __init__(self, call: Callable[[str, dict[str, Any]], Any]) -> None:".to_owned(),
        "        self._call = call".to_owned(),
    ];
    for method in &protocol.methods {
        lines.push(String::new());
        lines.push(format!("    {}", signature(method)));
        lines.push(docstring(&method.doc, 8));
        lines.push(format!("        {}", body(protocol, method)));
    }
    lines.join("\n")
}

fn signature(method: &MethodDecl) -> String {
    let parameters = if method.params == "Empty" {
        "self".to_owned()
    } else {
        format!("self, params: {}", method.params)
    };
    let result = if method.result == "Empty" {
        "None".to_owned()
    } else {
        python_type(&Ty::Named(method.result.clone()))
    };
    format!("def {}({parameters}) -> {result}:", attr(&method.wire))
}

fn body(protocol: &Protocol, method: &MethodDecl) -> String {
    let call = if method.params == "Empty" {
        format!("self._call({}, {{}})", py_string(&method.wire))
    } else {
        format!("self._call({}, params.to_json())", py_string(&method.wire))
    };
    if method.result == "Empty" {
        call
    } else {
        format!(
            "return {}",
            read_value(protocol, &Ty::Named(method.result.clone()), &call)
        )
    }
}

fn python_type(ty: &Ty) -> String {
    match ty {
        Ty::Bool => "bool".to_owned(),
        Ty::U32 | Ty::U64 | Ty::I64 => "int".to_owned(),
        Ty::F64 => "float".to_owned(),
        Ty::Str => "str".to_owned(),
        Ty::Option(inner) => format!("{} | None", python_type(inner)),
        Ty::Vec(inner) => format!("list[{}]", python_type(inner)),
        Ty::Named(name) => name.clone(),
    }
}

fn default(ty: &Ty) -> &'static str {
    match ty {
        Ty::Option(_) => " = None",
        Ty::Vec(_) => " = field(default_factory=list)",
        _ => "",
    }
}

fn has_default(ty: &Ty) -> bool {
    matches!(ty, Ty::Option(_) | Ty::Vec(_))
}

fn field_read(protocol: &Protocol, field: &Field) -> String {
    let key = json_key(&field.name);
    match &field.ty {
        Ty::Option(inner) => format!(
            "{} if data.get({key}) is not None else None",
            read_value(protocol, inner, &format!("data[{key}]"))
        ),
        Ty::Vec(inner) => format!(
            "[{} for v in data.get({key}, [])]",
            read_value(protocol, inner, "v")
        ),
        ty => read_value(protocol, ty, &format!("data[{key}]")),
    }
}

fn read_value(protocol: &Protocol, ty: &Ty, value: &str) -> String {
    match ty {
        Ty::Bool | Ty::U32 | Ty::U64 | Ty::I64 | Ty::F64 | Ty::Str => value.to_owned(),
        Ty::Option(inner) => format!(
            "({} if {value} is not None else None)",
            read_value(protocol, inner, value)
        ),
        Ty::Vec(inner) => format!("[{} for v in {value}]", read_value(protocol, inner, "v")),
        Ty::Named(name) => {
            match kind(protocol, name).expect("invariant: every named type is declared") {
                Kind::Record => format!("{name}.from_json({value})"),
                Kind::Choice => format!("{name}({value})"),
                Kind::Union => format!("{}_from_json({value})", snake(name)),
                Kind::Alias(ty) => read_value(protocol, ty, value),
            }
        }
    }
}

fn write_value(protocol: &Protocol, ty: &Ty, value: &str) -> String {
    match ty {
        Ty::Bool | Ty::U32 | Ty::U64 | Ty::I64 | Ty::F64 | Ty::Str => value.to_owned(),
        Ty::Option(inner) => format!(
            "({} if {value} is not None else None)",
            write_value(protocol, inner, value)
        ),
        Ty::Vec(inner) => format!("[{} for v in {value}]", write_value(protocol, inner, "v")),
        Ty::Named(name) => {
            match kind(protocol, name).expect("invariant: every named type is declared") {
                Kind::Record | Kind::Union => format!("{value}.to_json()"),
                Kind::Choice => format!("{value}.value"),
                Kind::Alias(ty) => write_value(protocol, ty, value),
            }
        }
    }
}

enum Kind<'a> {
    Record,
    Choice,
    Union,
    Alias(&'a Ty),
}

fn kind<'a>(protocol: &'a Protocol, name: &str) -> Option<Kind<'a>> {
    protocol.items.iter().find_map(|item| match item {
        Item::Record {
            name: item_name, ..
        } if item_name == name => Some(Kind::Record),
        Item::Choice {
            name: item_name, ..
        } if item_name == name => Some(Kind::Choice),
        Item::Union {
            name: item_name, ..
        } if item_name == name => Some(Kind::Union),
        Item::Alias {
            name: item_name,
            ty,
            ..
        } if item_name == name => Some(Kind::Alias(ty)),
        _ => None,
    })
}

fn attr(name: &str) -> String {
    if RESERVED.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

fn json_key(name: &str) -> String {
    format!("\"{name}\"")
}

fn py_string(text: &str) -> String {
    format!("\"{text}\"")
}

fn docstring(doc: &str, indent: usize) -> String {
    let escaped = doc.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    let mut lines = escaped.lines();
    let first = lines.next().unwrap_or("");
    let pad = " ".repeat(indent);
    let mut out = format!("{pad}\"\"\"{first}");
    for line in lines {
        out.push('\n');
        out.push_str(&pad);
        out.push_str(line);
    }
    out.push_str("\"\"\"");
    out
}
