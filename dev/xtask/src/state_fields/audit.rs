//! Role: Write the state audit required by design 6.4.

use std::path::{Path, PathBuf};

/// One counted field or local and how it is closed.
#[derive(Debug)]
pub(crate) struct AuditRow {
    pub(crate) path: PathBuf,
    pub(crate) line: usize,
    pub(crate) field: String,
    pub(crate) reason: String,
    pub(crate) closure: String,
}

/// How many rows have no marker and no type that closes them.
pub(crate) fn open_count(rows: &[AuditRow]) -> usize {
    rows.iter().filter(|row| row.closure == "OPEN").count()
}

/// The closure named by a marker reason (SL-8): its prefix before `:`.
pub(super) fn marker_closure(reason: &str) -> String {
    let reason = reason.trim();
    match reason.split_once(':') {
        Some((prefix, _)) if !prefix.trim().is_empty() => prefix.trim().to_owned(),
        _ if reason.is_empty() => "OPEN".to_owned(),
        _ => reason.to_owned(),
    }
}

/// Write `dev/xtask/state-audit.md` under `root`.
pub(crate) fn write(root: &Path, rows: &[AuditRow]) -> Result<(), String> {
    let mut rows: Vec<&AuditRow> = rows.iter().collect();
    rows.sort_by(|a, b| {
        a.path
            .cmp(&b.path)
            .then(a.line.cmp(&b.line))
            .then(a.field.cmp(&b.field))
    });
    let mut text = String::from(
        "# State audit\n\n\
         Generated by `cargo xtask check --only state-fields --report-audit` (design 6.4).\n\n\
         Every counted field or local of a struct, named variant or function that has two or more\n\
         state fields. `closure` is the marker reason prefix, `type` for an enum or Machine field,\n\
         and `OPEN` when the field has no closure.\n\n\
         | file:line | field | reason | closure |\n\
         |---|---|---|---|\n",
    );
    if rows.is_empty() {
        text.push_str("| - | - | - | - |\n");
    }
    for row in rows {
        let path = row.path.strip_prefix(root).unwrap_or(&row.path);
        text.push_str(&format!(
            "| {}:{} | {} | {} | {} |\n",
            path.to_string_lossy().replace('\\', "/"),
            row.line,
            escape(&row.field),
            escape(&row.reason),
            row.closure
        ));
    }
    let path = root.join("dev/xtask/state-audit.md");
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Keep table cells on one row.
fn escape(cell: &str) -> String {
    if cell.is_empty() {
        "-".to_owned()
    } else {
        cell.replace('|', "\\|")
    }
}
